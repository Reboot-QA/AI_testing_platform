/** 自然语言快捷意图（仅文字指引，不触发浏览器操作） */
export function resolveAssistantGuideAnswer(text: string): string | undefined {
  const t = text.trim()
  const exact = ASSISTANT_GUIDES.find((g) => g.text === t)
  if (exact) return exact.answer

  if (t.includes('报告') && /查看|打开|帮我|看|进入/.test(t)) {
    return `**查看测试报告**

1. 进入 **项目工作区** → 左侧 **自动化**。
2. 在左侧树打开 **测试报告**。
3. 点击列表中的记录或 **查看**，在抽屉中查看步骤明细、通过率，并可导出。`
  }

  return undefined
}
